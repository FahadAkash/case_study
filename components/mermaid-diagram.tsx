"use client";

import React, { useEffect, useState, useId } from "react";
import { Code, Eye, Copy, Check, ZoomIn, ZoomOut, RotateCcw } from "lucide-react";
import { cn } from "@/lib/utils";

interface MermaidDiagramProps {
  chart: string;
  title?: string;
  caption?: string;
  className?: string;
}

export function MermaidDiagram({ chart, title, caption, className = "" }: MermaidDiagramProps) {
  const [isClient, setIsClient] = useState(false);
  const [svgHtml, setSvgHtml] = useState<string>("");
  const [renderError, setRenderError] = useState<string | null>(null);
  const [viewMode, setViewMode] = useState<"diagram" | "code">("diagram");
  const [copied, setCopied] = useState(false);
  const [zoom, setZoom] = useState(1);

  // Stable unique ID
  const rawId = useId().replace(/[^a-zA-Z0-9]/g, "");
  const [chartId] = useState(() => `m_${rawId}_${Math.random().toString(36).substring(2, 8)}`);

  // Detect diagram type from chart syntax
  const trimmed = chart ? chart.trim() : "";
  const diagramType = trimmed.startsWith("erDiagram")
    ? "DATABASE ER SCHEMA"
    : trimmed.startsWith("sequenceDiagram")
    ? "SEQUENCE FLOW"
    : trimmed.startsWith("stateDiagram")
    ? "STATE MACHINE"
    : trimmed.startsWith("classDiagram")
    ? "CLASS ARCHITECTURE"
    : "SYSTEM TOPOLOGY";

  useEffect(() => {
    setIsClient(true);
  }, []);

  useEffect(() => {
    if (!isClient || !chart) return;

    let active = true;

    async function generateSvg() {
      try {
        const mermaid = (await import("mermaid")).default;

        mermaid.initialize({
          startOnLoad: false,
          securityLevel: "loose",
          fontFamily: "var(--font-mono), monospace",
          theme: "base",
          themeVariables: {
            primaryColor: "#FFFFFF",
            primaryTextColor: "#111111",
            primaryBorderColor: "#111111",
            lineColor: "#111111",
            secondaryColor: "#F4F4F1",
            secondaryTextColor: "#111111",
            secondaryBorderColor: "#666662",
            tertiaryColor: "#EAEAE5",
            tertiaryTextColor: "#111111",
            tertiaryBorderColor: "#C8C8BF",
            mainBkg: "#FFFFFF",
            nodeBorder: "#111111",
            clusterBkg: "#FBFBFA",
            clusterBorder: "#DEDED7",
            defaultLinkColor: "#111111",
            titleColor: "#111111",
            edgeLabelBackground: "#FFFFFF",
            actorBorder: "#111111",
            actorBkg: "#FFFFFF",
            actorTextColor: "#111111",
            actorLineColor: "#111111",
            signalColor: "#111111",
            signalTextColor: "#111111",
            labelBoxBkgColor: "#FFFFFF",
            labelBoxBorderColor: "#111111",
            labelTextColor: "#111111",
            loopTextColor: "#111111",
            noteBorderColor: "#111111",
            noteBkgColor: "#FBFBFA",
            noteTextColor: "#111111",
            activationBorderColor: "#111111",
            activationBkgColor: "#F4F4F1",
            sequenceNumberColor: "#FFFFFF",
            // ER Diagram variables
            attributeBackgroundColorOdd: "#FFFFFF",
            attributeBackgroundColorEven: "#F8F8F6",
            entityBorder: "#111111",
            entityBkg: "#FFFFFF",
            entityTextColor: "#111111",
          },
        });

        // Clean up any stale element from body before rendering
        const old = document.getElementById(chartId);
        if (old) old.remove();

        const { svg } = await mermaid.render(chartId, chart);

        // Remove temporary off-screen div generated by mermaid on body
        const stray = document.querySelectorAll(`[id^="d${chartId}"]`);
        stray.forEach((el) => el.remove());

        if (active) {
          setSvgHtml(svg);
          setRenderError(null);
        }
      } catch (err: any) {
        if (active) {
          console.error("Mermaid error:", err);
          setRenderError(err.message || "Failed to render Mermaid diagram.");
        }
      }
    }

    generateSvg();

    return () => {
      active = false;
      const old = document.getElementById(chartId);
      if (old) old.remove();
      const stray = document.querySelectorAll(`[id^="d${chartId}"]`);
      stray.forEach((el) => el.remove());
    };
  }, [isClient, chart, chartId]);

  const copyCode = () => {
    navigator.clipboard.writeText(chart);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className={cn("space-y-3", className)}>
      {title && (
        <div className="flex items-center gap-2">
          <span className="w-2 h-2 rounded-full bg-northfold-ink" />
          <h4 className="text-xs font-mono uppercase tracking-widest text-northfold-muted">
            {title}
          </h4>
        </div>
      )}

      <div className="rounded-2xl border border-northfold-border bg-white shadow-sm overflow-hidden transition-all hover:border-northfold-ink/40">
        {/* Top Control Bar */}
        <div className="flex items-center justify-between px-4 py-2.5 bg-northfold-surface border-b border-northfold-border text-xs font-mono">
          <div className="flex items-center gap-2">
            <span className="px-2.5 py-0.5 rounded-full bg-northfold-ink text-white text-[10px] uppercase tracking-wider font-semibold">
              {diagramType}
            </span>
          </div>

          <div className="flex items-center gap-2">
            {/* View Mode Toggle: Diagram vs Code */}
            <div className="flex rounded-full border border-northfold-border bg-white p-0.5 text-[11px]">
              <button
                type="button"
                onClick={() => setViewMode("diagram")}
                className={cn(
                  "px-2.5 py-1 rounded-full flex items-center gap-1 transition-colors",
                  viewMode === "diagram"
                    ? "bg-northfold-ink text-white font-medium"
                    : "text-northfold-muted hover:text-northfold-ink"
                )}
              >
                <Eye className="w-3 h-3" />
                <span>Diagram</span>
              </button>
              <button
                type="button"
                onClick={() => setViewMode("code")}
                className={cn(
                  "px-2.5 py-1 rounded-full flex items-center gap-1 transition-colors",
                  viewMode === "code"
                    ? "bg-northfold-ink text-white font-medium"
                    : "text-northfold-muted hover:text-northfold-ink"
                )}
              >
                <Code className="w-3 h-3" />
                <span>Source</span>
              </button>
            </div>

            {/* Zoom Controls (Diagram mode only) */}
            {viewMode === "diagram" && (
              <div className="hidden sm:flex items-center gap-1 border-l border-northfold-border pl-2">
                <button
                  type="button"
                  onClick={() => setZoom((prev) => Math.min(prev + 0.15, 2))}
                  className="p-1 rounded hover:bg-neutral-200 text-northfold-muted hover:text-northfold-ink"
                  title="Zoom In"
                >
                  <ZoomIn className="w-3.5 h-3.5" />
                </button>
                <button
                  type="button"
                  onClick={() => setZoom((prev) => Math.max(prev - 0.15, 0.6))}
                  className="p-1 rounded hover:bg-neutral-200 text-northfold-muted hover:text-northfold-ink"
                  title="Zoom Out"
                >
                  <ZoomOut className="w-3.5 h-3.5" />
                </button>
                <button
                  type="button"
                  onClick={() => setZoom(1)}
                  className="p-1 rounded hover:bg-neutral-200 text-northfold-muted hover:text-northfold-ink"
                  title="Reset Zoom"
                >
                  <RotateCcw className="w-3.5 h-3.5" />
                </button>
              </div>
            )}

            {/* Copy Button */}
            <button
              type="button"
              onClick={copyCode}
              className="p-1.5 rounded-md hover:bg-neutral-200 text-northfold-muted hover:text-northfold-ink transition-colors flex items-center gap-1"
              title="Copy Mermaid Code"
            >
              {copied ? (
                <Check className="w-3.5 h-3.5 text-emerald-600" />
              ) : (
                <Copy className="w-3.5 h-3.5" />
              )}
            </button>
          </div>
        </div>

        {/* Content Box */}
        <div className="p-6 overflow-x-auto min-h-[220px] flex items-center justify-center bg-[#FBFBFA]">
          {viewMode === "code" ? (
            <pre className="w-full text-xs font-mono text-neutral-800 bg-white p-4 rounded-xl border border-northfold-border leading-relaxed overflow-x-auto">
              <code>{chart}</code>
            </pre>
          ) : (
            <div className="w-full flex items-center justify-center">
              {renderError ? (
                <div className="space-y-3 text-center py-6">
                  <p className="text-xs font-mono text-amber-700 bg-amber-50 px-3 py-1.5 rounded-lg border border-amber-200 inline-block">
                    Could not render SVG: {renderError}
                  </p>
                  <pre className="text-xs font-mono text-neutral-600 bg-white p-3 rounded-lg border max-w-lg mx-auto text-left whitespace-pre-wrap">
                    {chart}
                  </pre>
                </div>
              ) : svgHtml ? (
                <div
                  style={{ transform: `scale(${zoom})`, transformOrigin: "center center" }}
                  className="w-full flex justify-center items-center transition-transform duration-200 [&>svg]:max-w-full [&>svg]:h-auto"
                  dangerouslySetInnerHTML={{ __html: svgHtml }}
                />
              ) : (
                <div className="text-xs font-mono text-northfold-muted animate-pulse">
                  Rendering architectural SVG topology...
                </div>
              )}
            </div>
          )}
        </div>
      </div>

      {caption && (
        <p className="text-xs font-mono text-northfold-muted text-center tracking-wide">
          {caption}
        </p>
      )}
    </div>
  );
}
